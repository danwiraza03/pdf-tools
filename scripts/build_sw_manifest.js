/**
 * Build Script: Generate Service Worker Manifest & Update sw.js
 * Computes SHA-256 hashes for all App Shell files (< 5 MB) and generates:
 * - sw-manifest.json (audit trail & version manifest)
 * - sw.js (production service worker with embedded version and precache list)
 */

'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT_DIR = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT_DIR, 'sw-manifest.json');
const SW_PATH = path.join(ROOT_DIR, 'sw.js');

function hashFile(fullPath) {
  const content = fs.readFileSync(fullPath);
  return crypto.createHash('sha256').update(content).digest('hex');
}

function getAppShellFileList() {
  const files = [
    'index.html',
    'manifest.json',
    'icon.svg',
    'icons/icon-192.png',
    'icons/icon-512.png',
    'css/style.css',
    'css/home.css',
    'css/tool.css',
    'js/app.js',
    'js/components/header.js',
    'js/components/modal.js',
    'js/components/toast.js',
    'js/components/dropzone.js',
    'js/utils/i18n.js',
    'js/utils/file-utils.js',
    'js/utils/download.js',
    'js/lib/pdf-lib.min.js',
    'js/lib/pdf.min.js',
    'js/lib/pdf.worker.min.js',
    'js/lib/jszip.min.js',
    'js/lib/Sortable.min.js',
    'js/lib/FileSaver.min.js'
  ];

  // Standalone pages (strictly excluding viewer.html to keep precache < 5 MB)
  const pagesDir = path.join(ROOT_DIR, 'pages');
  fs.readdirSync(pagesDir).forEach(f => {
    if (f.endsWith('.html') && f !== 'viewer.html') {
      files.push(`pages/${f}`);
    }
  });

  // Core JS modules (excluding pdf-ocr.js and pdf-studio.js)
  const coreDir = path.join(ROOT_DIR, 'js/core');
  fs.readdirSync(coreDir).forEach(f => {
    if (f.endsWith('.js') && f !== 'pdf-ocr.js' && f !== 'pdf-studio.js') {
      files.push(`js/core/${f}`);
    }
  });

  // Fonts (Inter Latin subsets for weights 400, 500, 600, 700, 800)
  ['400', '500', '600', '700', '800'].forEach(w => {
    files.push(`fonts/inter-latin-${w}-normal.woff2`);
  });

  return files.sort();
}

function buildManifest() {
  const files = getAppShellFileList();
  const fileEntries = [];
  let totalBytes = 0;
  const hashCollector = crypto.createHash('sha256');

  for (const rel of files) {
    const fullPath = path.join(ROOT_DIR, rel);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`File required for app shell not found: ${rel}`);
    }
    const stat = fs.statSync(fullPath);
    const hash = hashFile(fullPath);
    totalBytes += stat.size;
    hashCollector.update(`${rel}:${hash};`);

    fileEntries.push({
      url: `./${rel}`,
      size: stat.size,
      hash: hash.slice(0, 12)
    });
  }

  const compositeHash = hashCollector.digest('hex');
  const cacheVersion = `pdf-tools-v${compositeHash.slice(0, 10)}`;

  const manifest = {
    version: cacheVersion,
    compositeHash,
    builtAt: new Date().toISOString(),
    totalFiles: fileEntries.length,
    totalBytes,
    totalMB: (totalBytes / (1024 * 1024)).toFixed(2),
    files: fileEntries
  };

  return manifest;
}

function generateServiceWorkerCode(manifest) {
  const precacheUrlsJson = JSON.stringify(manifest.files.map(f => f.url), null, 2);

  return `/**
 * PDF Tools — Production Offline Service Worker
 * Generated by scripts/build_sw_manifest.js
 * 100% Client-Side Offline Support & Privacy-Preserving Cache
 *
 * CACHE VERSION: ${manifest.version}
 * TOTAL APP SHELL SIZE: ${manifest.totalMB} MB (${manifest.totalFiles} files)
 */

'use strict';

const CACHE_VERSION = '${manifest.version}';
const APP_SHELL_CACHE = CACHE_VERSION + '-shell';
const RUNTIME_CACHE = CACHE_VERSION + '-runtime';

// Relative App Shell URLs to precache during install
const PRECACHE_URLS = ${precacheUrlsJson};

// Helper: resolve relative URL to absolute URL within current scope
function resolveUrl(relativeUrl) {
  return new URL(relativeUrl, self.registration.scope).toString();
}

// 1. INSTALL LIFECYCLE
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(APP_SHELL_CACHE).then(async (cache) => {
      console.log('[SW] Precaching App Shell (' + PRECACHE_URLS.length + ' files, ' + '${manifest.totalMB}' + ' MB)...');
      const absoluteUrls = PRECACHE_URLS.map(resolveUrl);
      
      // Cache with allSettled to ensure resilient install even if a minor asset fails
      const fetchPromises = absoluteUrls.map(async (url) => {
        try {
          const res = await fetch(url, { cache: 'no-cache' });
          if (res && res.status === 200) {
            await cache.put(url, res);
          }
        } catch (err) {
          console.warn('[SW] Precache item failed:', url, err.message);
        }
      });
      await Promise.all(fetchPromises);
      console.log('[SW] Precache completed successfully.');
    })
  );
});

// 2. ACTIVATE LIFECYCLE
self.addEventListener('activate', (event) => {
  const allowedCaches = new Set([APP_SHELL_CACHE, RUNTIME_CACHE]);
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((name) => {
          if (!allowedCaches.has(name) && name.startsWith('pdf-tools-')) {
            console.log('[SW] Deleting stale cache:', name);
            return caches.delete(name);
          }
          return Promise.resolve();
        })
      );
    }).then(() => {
      console.log('[SW] Claiming clients for version:', CACHE_VERSION);
      return self.clients.claim();
    })
  );
});

// 3. FETCH STRATEGY
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);

  // PRIVACY & SECURITY GUARD:
  // - Only handle GET requests
  // - Only handle same-origin requests under our scope
  // - NEVER cache blob:, data:, or non-http(s) schemes
  // - NEVER cache user upload payloads or external tracking
  if (request.method !== 'GET') return;
  if (url.origin !== self.location.origin) return;
  if (!url.protocol.startsWith('http')) return;
  if (!url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;

  // A. NAVIGATION REQUESTS (HTML Pages): Network-first with Cache fallback
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const responseToCache = networkResponse.clone();
          caches.open(APP_SHELL_CACHE).then((cache) => {
            cache.put(request, responseToCache);
          });
        }
        return networkResponse;
      }).catch(async () => {
        // Fallback to cache for the specific page
        const cachedResponse = await caches.match(request);
        if (cachedResponse) return cachedResponse;
        
        // Final fallback to cached index.html
        return caches.match(resolveUrl('./index.html'));
      })
    );
    return;
  }

  // B. STATIC ASSETS (CSS, JS, Fonts, Images): Cache-first with Network fallback
  event.respondWith(
    caches.match(request).then((cachedResponse) => {
      if (cachedResponse) {
        return cachedResponse;
      }

      // Not in cache: fetch from network and dynamically cache runtime assets (e.g. OCR / viewer)
      return fetch(request).then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const responseToCache = networkResponse.clone();
          // Store runtime on-demand assets in RUNTIME_CACHE
          caches.open(RUNTIME_CACHE).then((cache) => {
            cache.put(request, responseToCache);
          });
        }
        return networkResponse;
      });
    })
  );
});

// 4. MESSAGE LISTENER (Skip Waiting on User Reload)
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    console.log('[SW] Skip waiting triggered by user reload action.');
    self.skipWaiting();
  }
});
`;
}

function writeOutputs() {
  const manifest = buildManifest();

  // 1. Write sw-manifest.json
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2), 'utf8');
  console.log(`✓ Wrote sw-manifest.json: ${manifest.version} (${manifest.totalFiles} files, ${manifest.totalMB} MB)`);

  // 2. Write sw.js
  const swCode = generateServiceWorkerCode(manifest);
  fs.writeFileSync(SW_PATH, swCode, 'utf8');
  console.log(`✓ Generated production sw.js with cache version ${manifest.version}`);

  return manifest;
}

if (require.main === module) {
  try {
    writeOutputs();
  } catch (err) {
    console.error('Fatal error building Service Worker manifest:', err);
    process.exit(1);
  }
}

module.exports = {
  getAppShellFileList,
  buildManifest,
  writeOutputs
};
